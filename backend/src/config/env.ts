/**
 * Typed environment configuration. Fails fast in production; in development
 * and test, missing external-service credentials surface as
 * SERVICE_NOT_CONFIGURED (503) at call time — never as fake behaviour.
 */
import dotenv from 'dotenv';
dotenv.config();

const str = (v: string | undefined, fallback = ''): string => (v ?? fallback).trim();
const num = (v: string | undefined, fallback: number): number => {
  const n = Number(v);
  return Number.isFinite(n) && n > 0 ? n : fallback;
};

const nodeEnv = str(process.env.NODE_ENV, 'development');

export const env = {
  nodeEnv,
  isProduction: nodeEnv === 'production',
  isTest: nodeEnv === 'test',
  port: num(process.env.PORT, 4000),
  logLevel: str(process.env.LOG_LEVEL, 'info'),
  corsOrigin: str(process.env.CORS_ORIGIN, 'http://localhost:4173')
    .split(',')
    .map((s) => s.trim())
    .filter(Boolean),

  clerk: {
    secretKey: str(process.env.CLERK_SECRET_KEY),
    publishableKey: str(process.env.CLERK_PUBLISHABLE_KEY),
    webhookSigningSecret: str(process.env.CLERK_WEBHOOK_SIGNING_SECRET),
  },

  supabase: {
    url: str(process.env.SUPABASE_URL),
    anonKey: str(process.env.SUPABASE_ANON_KEY),
    serviceRoleKey: str(process.env.SUPABASE_SERVICE_ROLE_KEY),
  },

  twilio: {
    accountSid: str(process.env.TWILIO_ACCOUNT_SID),
    authToken: str(process.env.TWILIO_AUTH_TOKEN),
    fromNumber: str(process.env.TWILIO_FROM_NUMBER),
    allowedRecipients: str(process.env.TWILIO_ALLOWED_RECIPIENTS)
      .split(',')
      .map((s) => s.trim())
      .filter(Boolean),
    smsPerHour: num(process.env.RATE_LIMIT_SMS_PER_HOUR, 20),
  },

  payments: {
    provider: str(process.env.PAYMENT_PROVIDER, 'manual-review'),
    webhookSecret: str(process.env.PAYMENT_WEBHOOK_SECRET),
  },

  rateLimit: {
    windowMs: num(process.env.RATE_LIMIT_WINDOW_MS, 60_000),
    max: num(process.env.RATE_LIMIT_MAX, 300),
    depositPerMin: num(process.env.RATE_LIMIT_DEPOSIT_PER_MIN, 10),
    supportPerMin: num(process.env.RATE_LIMIT_SUPPORT_PER_MIN, 5),
  },

  statementNote: str(
    process.env.STATEMENT_NOTE,
    'Generated by Meridian Global Accounts (provisional format)',
  ),
} as const;

/** Called at boot: refuse to start in production with missing secrets. */
export function assertProductionReadiness(): void {
  if (!env.isProduction) return;
  const missing: string[] = [];
  if (!env.clerk.secretKey) missing.push('CLERK_SECRET_KEY');
  if (!env.clerk.webhookSigningSecret) missing.push('CLERK_WEBHOOK_SIGNING_SECRET');
  if (!env.supabase.url) missing.push('SUPABASE_URL');
  if (!env.supabase.anonKey) missing.push('SUPABASE_ANON_KEY');
  if (!env.supabase.serviceRoleKey) missing.push('SUPABASE_SERVICE_ROLE_KEY');
  if (missing.length > 0) {
    throw new Error(`Refusing to start in production without: ${missing.join(', ')}`);
  }
}

/** True when a Supabase project is configured (dev convenience gate). */
export function supabaseConfigured(): boolean {
  return Boolean(env.supabase.url && env.supabase.anonKey && env.supabase.serviceRoleKey);
}
