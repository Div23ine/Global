/**
 * Typed environment configuration.
 * Works under Node (process.env + dotenv) and Cloudflare Workers
 * (bindings injected via applyWorkerEnv before request handling).
 * Missing external credentials surface as SERVICE_NOT_CONFIGURED — never fake behaviour.
 */

// dotenv is Node-only; skip on Workers
try {
  // eslint-disable-next-line @typescript-eslint/no-require-imports
  require('dotenv').config();
} catch {
  /* Workers / edge — no dotenv */
}

const str = (v: string | undefined, fallback = ''): string => (v ?? fallback).trim();
const num = (v: string | undefined, fallback: number): number => {
  const n = Number(v);
  return Number.isFinite(n) && n > 0 ? n : fallback;
};

/** Mutable bag so Worker bindings can be applied once per isolate. */
const bag: Record<string, string | undefined> = {};

function get(key: string): string | undefined {
  if (key in bag && bag[key] !== undefined) return bag[key];
  if (typeof process !== 'undefined' && process.env) return process.env[key];
  return undefined;
}

function buildEnv() {
  const nodeEnv = str(get('NODE_ENV'), 'development');
  return {
    nodeEnv,
    isProduction: nodeEnv === 'production',
    isTest: nodeEnv === 'test',
    port: num(get('PORT'), 4000),
    logLevel: str(get('LOG_LEVEL'), 'info'),
    corsOrigin: str(get('CORS_ORIGIN'), 'http://localhost:4173')
      .split(',')
      .map((s) => s.trim())
      .filter(Boolean),

    clerk: {
      secretKey: str(get('CLERK_SECRET_KEY')),
      publishableKey: str(get('CLERK_PUBLISHABLE_KEY')),
      webhookSigningSecret: str(get('CLERK_WEBHOOK_SIGNING_SECRET')),
    },

    supabase: {
      url: str(get('SUPABASE_URL')),
      anonKey: str(get('SUPABASE_ANON_KEY')),
      serviceRoleKey: str(get('SUPABASE_SERVICE_ROLE_KEY')),
    },

    twilio: {
      accountSid: str(get('TWILIO_ACCOUNT_SID')),
      authToken: str(get('TWILIO_AUTH_TOKEN')),
      fromNumber: str(get('TWILIO_FROM_NUMBER')),
      allowedRecipients: str(get('TWILIO_ALLOWED_RECIPIENTS'))
        .split(',')
        .map((s) => s.trim())
        .filter(Boolean),
      smsPerHour: num(get('RATE_LIMIT_SMS_PER_HOUR'), 20),
    },

    resend: {
      apiKey: str(get('RESEND_API_KEY')),
      fromEmail: str(get('RESEND_FROM_EMAIL')),
      fromName: str(get('RESEND_FROM_NAME'), 'Meridian Global Accounts'),
    },

    payments: {
      provider: str(get('PAYMENT_PROVIDER'), 'manual-bank-transfer'),
      webhookSecret: str(get('PAYMENT_WEBHOOK_SECRET')),
    },

    rateLimit: {
      windowMs: num(get('RATE_LIMIT_WINDOW_MS'), 60_000),
      max: num(get('RATE_LIMIT_MAX'), 300),
      depositPerMin: num(get('RATE_LIMIT_DEPOSIT_PER_MIN'), 10),
      supportPerMin: num(get('RATE_LIMIT_SUPPORT_PER_MIN'), 5),
    },

    statementNote: str(
      get('STATEMENT_NOTE'),
      'Generated by Meridian Global Accounts (provisional format)',
    ),
  } as const;
}

export type AppEnv = ReturnType<typeof buildEnv>;

/** Live env object — rebuild after applyWorkerEnv. */
export let env: AppEnv = buildEnv();

/**
 * Check whether all credentials required by both Supabase clients are configured.
 * This checks configuration only; it does not test network reachability.
 */
export function supabaseConfigured(): boolean {
  return Boolean(
    env.supabase.url &&
    env.supabase.anonKey &&
    env.supabase.serviceRoleKey
  );
}

/**
 * Apply Cloudflare Worker secrets/vars into the env bag and rebuild.
 * Call once at the start of each fetch (or on isolate init).
 */
export function applyWorkerEnv(bindings: Record<string, unknown>): void {
  for (const [k, v] of Object.entries(bindings)) {
    if (typeof v === 'string' || typeof v === 'undefined') {
      bag[k] = v;
      if (typeof process !== 'undefined' && process.env) {
        process.env[k] = v ?? '';
      }
    }
  }
  env = buildEnv();
}

/** Called at boot: refuse to start in production with missing secrets. */
export function assertProductionReadiness(): void {
  if (!env.isProduction) return;
  const missing: string[] = [];
  if (!env.clerk.secretKey) missing.push('CLERK_SECRET_KEY');
  if (!env.clerk.webhookSigningSecret) missing.push('CLERK_WEBHOOK_SIGNING_SECRET');
  if (!env.supabase.url) missing.push('SUPABASE_URL');
  if (!env.supabase.anonKey) missing.push('SUPABASE_ANON_KEY');
  if (!env.supabase.serviceRoleKey) missing.push('SUPABASE_SERVICE_ROLE_KEY');
  if (missing.length) {
    throw new Error(`Production missing required secrets: ${missing.join(', ')}`);
  }
}
